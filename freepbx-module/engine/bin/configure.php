#!/usr/bin/env php
<?php
/**
 * bin/configure.php - minimal config.ini writer for boxes with no
 * management GUI (Issabel, plain Asterisk - see frontends/generic).
 *
 * Two modes:
 *   Scripted:    php configure.php --endpoint=... --api-key=... [--out=/path]
 *   Interactive: php configure.php            (prompts for each value,
 *                                               reads existing file as
 *                                               defaults if present)
 *
 * Writes a full config.ini built from Engine\Config::DEFAULTS with the
 * given overrides applied - the same single source of truth every other
 * entry point reads (plan.md §3.4 / §3.6).
 */

require __DIR__ . '/../autoload.php';

use Engine\Config;

function configure_flag_value(array $argv, string $name): ?string
{
    $prefix = "--{$name}=";
    foreach ($argv as $arg) {
        if (str_starts_with($arg, $prefix)) {
            return substr($arg, strlen($prefix));
        }
    }
    return null;
}

function configure_prompt(string $label, string $default): string
{
    $suffix = $default !== '' ? " [{$default}]" : '';
    fwrite(STDOUT, "{$label}{$suffix}: ");
    $line = fgets(STDIN);
    $line = $line === false ? '' : trim($line);
    return $line === '' ? $default : $line;
}

function configure_write_ini(array $cfg, string $path): void
{
    $lines = [];
    $lines[] = '; Generated by bin/configure.php - see engine/config/config.ini.example';
    $lines[] = '; for a fully-commented reference copy.';
    $lines[] = '';
    foreach ($cfg as $section => $keys) {
        $lines[] = "[{$section}]";
        foreach ($keys as $key => $value) {
            if (is_bool($value)) {
                $value = $value ? 'true' : 'false';
            }
            $lines[] = "{$key} = {$value}";
        }
        $lines[] = '';
    }
    $dir = dirname($path);
    if (!is_dir($dir)) {
        mkdir($dir, 0755, true);
    }
    file_put_contents($path, implode("\n", $lines));
    fwrite(STDOUT, "Wrote {$path}\n");
}

function configure_main(array $argv): int
{
    $outPath = configure_flag_value($argv, 'out') ?? Config::DEFAULT_CONFIG_PATH;
    $existing = is_file($outPath) ? Config::load($outPath) : Config::DEFAULTS;

    $scripted = false;
    foreach ($argv as $arg) {
        if (str_starts_with($arg, '--') && strpos($arg, '=') !== false && !str_starts_with($arg, '--out=')) {
            $scripted = true;
            break;
        }
    }

    $cfg = $existing;

    // Map the handful of settings someone actually needs to touch on a
    // first-run scripted install; anything else can be hand-edited in
    // the written file afterwards.
    $fieldMap = [
        'endpoint' => ['general', 'endpoint'],
        'api-key' => ['general', 'api_key'],
        'archive-password' => ['general', 'archive_password'],
        'watch-dir' => ['watcher', 'watch_dir'],
        'gzip' => ['upload', 'gzip'],
        'archive-format' => ['archive', 'format'],
    ];

    if ($scripted) {
        foreach ($fieldMap as $flag => [$section, $key]) {
            $val = configure_flag_value($argv, $flag);
            if ($val !== null) {
                $cfg[$section][$key] = is_bool($cfg[$section][$key]) ? in_array(strtolower($val), ['1', 'true', 'yes'], true) : $val;
            }
        }
    } else {
        fwrite(STDOUT, "Asterisk Recording Uploader - interactive configuration\n");
        fwrite(STDOUT, "Press Enter to keep the default/current value shown in [brackets].\n\n");
        $cfg['general']['endpoint'] = configure_prompt('Ingest endpoint URL', $cfg['general']['endpoint']);
        $cfg['general']['api_key'] = configure_prompt('API key', $cfg['general']['api_key']);
        $cfg['general']['archive_password'] = configure_prompt(
            'AES-256 ZIP archive password (blank = disabled)', $cfg['general']['archive_password']
        );
        $cfg['watcher']['watch_dir'] = configure_prompt('Asterisk recording directory', $cfg['watcher']['watch_dir']);
        $cfg['archive']['format'] = configure_prompt('Local archive format', $cfg['archive']['format']);
    }

    configure_write_ini($cfg, $outPath);
    return 0;
}

exit(configure_main($argv));
