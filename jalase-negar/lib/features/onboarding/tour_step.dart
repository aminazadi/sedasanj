  static TourStep? fromUri(Uri uri) {
    final name = uri.queryParameters['tour'];
    for (final step in values) {
      if (step.name == name && step.path == uri.path) return step;
    }
    return null;
  }

  String location({bool fromSettings = false}) => Uri(
    path: path,
    queryParameters: {'tour': name, if (fromSettings) 'from': 'settings'},
  ).toString();
