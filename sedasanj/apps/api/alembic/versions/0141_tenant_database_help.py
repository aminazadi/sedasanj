def _slug(code: str) -> str:
    return code.lower().replace("_", "-")


def error_body(code: str, cause: str, steps: list[str], verify: str, prevent: str) -> str:
    items = "".join(f"<li>{step}</li>" for step in steps)
    return (
        f'<h2>نشانه‌ها</h2><p>در صفحهٔ دیتابیس سازمان‌ها کد <code dir="ltr">{code}</code> دیده می‌شود.</p>'
        f"<h2>علت</h2><p>{cause}</p>"
        f"<h2>رفع مشکل</h2><ol>{items}</ol>"
        f"<h2>تأیید رفع مشکل</h2><p>{verify}</p>"
        f"<h2>پیشگیری</h2><p>{prevent}</p>"
    )


def upgrade() -> None:
    bind = op.get_bind()
    for code, title, severity, cause, steps, quick, verify, prevent in ERRORS:
        slug = _slug(code)
        body = error_body(code, cause, steps, verify, prevent)
        bind.execute(
            sa.text(
                "INSERT INTO help_articles (slug, title, summary, body_html, body_plain, kind, "
                "status, position, published_at) VALUES (:slug, :title, :summary, :body, "
                ":plain, 'article', 'published', 160, now()) ON CONFLICT (slug) DO NOTHING"
            ),
            {
                "slug": slug,
                "title": title,
                "summary": f"توضیح خطای {code} و اقدام بعدی.",
                "body": body,
                "plain": f"{title} {code} {cause} {quick}",
            },
        )
        bind.execute(
            sa.text(
                "INSERT INTO help_error_codes (code, article_id, source, severity, title, quick_action) "
                "SELECT :code, id, 'worker', :severity, :title, :quick FROM help_articles "
                "WHERE slug = :slug ON CONFLICT (code) DO NOTHING"
            ),
            {"code": code, "severity": severity, "title": title, "quick": quick, "slug": slug},
        )


def downgrade() -> None:
    bind = op.get_bind()
    bind.execute(
        sa.text("DELETE FROM help_error_codes WHERE code = ANY(:codes)"),
        {"codes": [item[0] for item in ERRORS]},
    )
    bind.execute(
        sa.text("DELETE FROM help_articles WHERE slug = ANY(:slugs)"),
        {"slugs": [_slug(item[0]) for item in ERRORS]},
    )
